// Fuzzes the per-controller HID input report parsers (DS3/DS4/DS5, Xbox, Switch, Wii, Steam, Stadia, Atari,
// keyboard, mouse, generic descriptor-driven, ...).
// Input: byte 0 selects the controller type, the rest is the input report as received over Bluetooth.
#include "fuzz_common.h"

#include "parser/uni_hid_parser.h"

// Used for devices whose parser has no built-in descriptor, so the descriptor-driven (parse_usage)
// parsers run too: gamepad axes, hat, triggers, 16 buttons, keyboard array.
static const uint8_t g_fallback_descriptor[] = {
    0x05, 0x01, 0x09, 0x05, 0xa1, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35, 0x15, 0x81,
    0x25, 0x7f, 0x75, 0x08, 0x95, 0x04, 0x81, 0x02, 0x09, 0x39, 0x15, 0x00, 0x25, 0x07, 0x75, 0x04,
    0x95, 0x01, 0x81, 0x42, 0x75, 0x04, 0x95, 0x01, 0x81, 0x01, 0x05, 0x02, 0x09, 0xc5, 0x09, 0xc4,
    0x15, 0x00, 0x26, 0xff, 0x00, 0x75, 0x08, 0x95, 0x02, 0x81, 0x02, 0x05, 0x09, 0x19, 0x01, 0x29,
    0x10, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x10, 0x81, 0x02, 0x05, 0x07, 0x19, 0x00, 0x29,
    0x65, 0x15, 0x00, 0x25, 0x65, 0x75, 0x08, 0x95, 0x02, 0x81, 0x00, 0xc0,
};

int LLVMFuzzerInitialize(int* argc, char*** argv) {
    (void)argc;
    (void)argv;
    fuzz_stack_init();
    return 0;
}

int LLVMFuzzerTestOneInput(const uint8_t* data, size_t size) {
    static uni_hid_device_t d;
    if (size < 1 || size > 1 + 512) {
        return -1;
    }
    fuzz_setup_device(&d, data[0]);
    if (d.hid_descriptor_len == 0) {
        uni_hid_device_set_hid_descriptor(&d, g_fallback_descriptor, sizeof(g_fallback_descriptor));
    }
    uni_hid_parse_input_report(&d, data + 1, (uint16_t)(size - 1));
    btstack_run_loop_base_timers = NULL;
    return 0;
}
